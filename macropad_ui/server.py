#!/usr/bin/env python3
"""MacroPad UI - a local web UI for programming CH57x macro keyboards.

It wraps the command-line tool `ch57x-keyboard-tool`
(https://github.com/kriomant/ch57x-keyboard-tool), which does the actual USB work.

Usage:
    python3 server.py [--port 8777] [--no-open] [--tool PATH] [--configs DIR]

The server only listens on 127.0.0.1.
"""
import argparse
import json
import os
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import threading
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlparse

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required:  pip3 install pyyaml")

HERE = Path(__file__).resolve().parent
SYSTEM = platform.system()
VENDOR = "0x1189"
PRODUCTS = {0x8840, 0x8842, 0x8890}
NAME_RE = re.compile(r"^[A-Za-z0-9._ -]{1,60}$")
PERM_RE = re.compile(r"denied|permission|privilege|access", re.I)

# Filled in by main()
PORT = 8777
TOOL = None            # Path | None
CONFIGS = None         # Path
DATA = None            # Path
STATE_FILE = None      # Path: remembers the last config / working draft between runs


# --------------------------------------------------------------------------- setup
def find_tool(cli_value=None):
    """Locate ch57x-keyboard-tool: --tool, $MACROPAD_TOOL, ./bin, PATH, common install dirs."""
    candidates = [cli_value, os.environ.get("MACROPAD_TOOL"), HERE.parent / "bin" / "ch57x-keyboard-tool",
                  shutil.which("ch57x-keyboard-tool"),
                  Path.home() / ".cargo" / "bin" / "ch57x-keyboard-tool",
                  "/opt/homebrew/bin/ch57x-keyboard-tool", "/usr/local/bin/ch57x-keyboard-tool"]
    for c in candidates:
        if c and Path(c).is_file() and os.access(c, os.X_OK):
            return Path(c)
    return None


def default_data_dir():
    if SYSTEM == "Darwin":
        return Path.home() / "Library" / "Application Support" / "MacroPad UI"
    return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "macropad-ui"


def seed_configs():
    CONFIGS.mkdir(parents=True, exist_ok=True)
    if any(CONFIGS.glob("*.yaml")):
        return
    for f in (HERE / "examples").glob("*.yaml"):
        shutil.copy(f, CONFIGS / f.name)


def read_state():
    try:
        return json.loads(STATE_FILE.read_text())
    except Exception:
        return {}


def write_state(**kw):
    st = read_state()
    st.update(kw)
    STATE_FILE.write_text(json.dumps(st))


# --------------------------------------------------------------------------- YAML
def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_yaml(cfg):
    """Render the config in the same style as the upstream example-mapping.yaml."""
    out = [
        "# Generated by MacroPad UI",
        f"orientation: {cfg['orientation']}",
        f"rows: {int(cfg['rows'])}",
        f"columns: {int(cfg['columns'])}",
        f"knobs: {int(cfg['knobs'])}",
        "",
        "layers:",
    ]

    def val(v):
        return "null" if v in (None, "") else q(v)

    for layer in cfg["layers"]:
        out.append("  - buttons:")
        for row in layer["buttons"]:
            out.append("      - [" + ", ".join(val(v) for v in row) + "]")
        if not layer["knobs"]:
            out.append("    knobs: []")
        else:
            out.append("    knobs:")
            for k in layer["knobs"]:
                out.append(f"      - ccw: {val(k.get('ccw'))}")
                out.append(f"        press: {val(k.get('press'))}")
                out.append(f"        cw: {val(k.get('cw'))}")
        out.append("")
    return "\n".join(out)


def load_cfg(path):
    return cfg_from_raw(yaml.safe_load(path.read_text()))


def cfg_from_raw(raw):
    if not isinstance(raw, dict) or not isinstance(raw.get("layers"), list):
        raise ValueError("not a keyboard config (missing 'layers')")
    layers = []
    for layer in raw.get("layers", []):
        layers.append({
            "buttons": [[("" if v is None else str(v)) for v in row] for row in layer.get("buttons", [])],
            "knobs": [{a: ("" if k.get(a) is None else str(k.get(a))) for a in ("ccw", "press", "cw")}
                      for k in layer.get("knobs") or []],
        })
    return {
        "orientation": raw.get("orientation", "normal"),
        "rows": raw.get("rows", 3),
        "columns": raw.get("columns", 4),
        "knobs": raw.get("knobs", 0),
        "layers": layers,
    }


# --------------------------------------------------------------------------- tool + device
def run_tool(args, stdin=None, timeout=30):
    if TOOL is None:
        return 127, "ch57x-keyboard-tool not found"
    try:
        p = subprocess.run([str(TOOL), *args], input=stdin, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return 124, "Timed out."
    return p.returncode, (p.stdout + p.stderr).strip()


def detect_device():
    try:
        if SYSTEM == "Darwin":
            txt = subprocess.run(["ioreg", "-p", "IOUSB", "-l", "-w0"], capture_output=True, text=True, timeout=10).stdout
            for block in re.split(r"\+-o ", txt):
                v = re.search(r'"idVendor" = (\d+)', block)
                p = re.search(r'"idProduct" = (\d+)', block)
                if v and p and int(v.group(1)) == 0x1189 and int(p.group(1)) in PRODUCTS:
                    return f"{int(v.group(1)):04x}:{int(p.group(1)):04x}"
        elif SYSTEM == "Linux":
            txt = subprocess.run(["lsusb"], capture_output=True, text=True, timeout=10).stdout
            m = re.search(r"ID (1189):(8840|8842|8890)", txt)
            if m:
                return f"{m.group(1)}:{m.group(2)}"
    except Exception:
        pass
    return None


def list_keys():
    _, out = run_tool(["show-keys"])
    sections, cur = {}, None
    for line in out.splitlines():
        line = line.rstrip()
        if line.endswith(":") and not line.startswith(" "):
            cur = line[:-1].strip()
            sections[cur] = []
        elif line.startswith(" - ") and cur:
            sections[cur].append([n.strip() for n in line[3:].split(" / ")])
    return sections


def mac_admin_run(args):
    """Run the tool with administrator rights through the native macOS password dialog."""
    cmd = shlex.quote(str(TOOL)) + " --vendor-id " + VENDOR + " " + " ".join(shlex.quote(a) for a in args) + " 2>&1"
    script = f"do shell script {q(cmd)} with administrator privileges"
    p = subprocess.run(["osascript", "-e", script], capture_output=True, text=True, timeout=120)
    return p.returncode, (p.stdout + p.stderr).strip()


def privileged(args, text=None):
    """Try without privileges first; on a permission error, escalate (macOS dialog)."""
    code, out = run_tool(["--vendor-id", VENDOR, *args[:1], *(args[1:] if text is None else [])],
                         stdin=text)
    if code != 0 and PERM_RE.search(out) and SYSTEM == "Darwin" and TOOL is not None:
        if text is None:
            return mac_admin_run(args)
        with tempfile.TemporaryDirectory() as d:
            f = Path(d) / "upload.yaml"
            f.write_text(text)
            f.chmod(0o644)
            Path(d).chmod(0o755)
            return mac_admin_run([args[0], str(f)])
    return code, out


# --------------------------------------------------------------------------- HTTP
class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def _ok_origin(self):
        if self.headers.get("Host", "") not in (f"127.0.0.1:{PORT}", f"localhost:{PORT}"):
            return False
        origin = self.headers.get("Origin")
        return origin is None or origin in (f"http://127.0.0.1:{PORT}", f"http://localhost:{PORT}")

    def _send(self, obj, status=200, ctype="application/json"):
        body = obj if isinstance(obj, bytes) else json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", ctype + "; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _err(self, code, message, status=400):
        self._send({"error": message, "code": code}, status)

    def do_GET(self):
        if not self._ok_origin():
            return self._err("forbidden", "forbidden", 403)
        u = urlparse(self.path)
        if u.path == "/":
            return self._send((HERE / "index.html").read_bytes(), ctype="text/html")
        if u.path == "/api/state":
            st = read_state()
            return self._send({"device": detect_device(), "keys": list_keys(), "tool": TOOL is not None,
                               "platform": SYSTEM, "configs": sorted(p.stem for p in CONFIGS.glob("*.yaml")),
                               "last": st.get("last"), "draft": st.get("draft")})
        if u.path == "/api/device":
            return self._send({"device": detect_device()})
        if u.path == "/api/config":
            name = unquote(parse_qs(u.query).get("name", [""])[0])
            f = CONFIGS / f"{name}.yaml"
            if not NAME_RE.match(name) or not f.exists():
                return self._err("not_found", "Config not found", 404)
            try:
                return self._send(load_cfg(f))
            except Exception as e:
                return self._err("bad_yaml", f"Unreadable YAML: {e}")
        self._err("not_found", "not found", 404)

    def do_POST(self):
        if not self._ok_origin() or "application/json" not in self.headers.get("Content-Type", ""):
            return self._err("forbidden", "forbidden", 403)
        try:
            data = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))) or b"{}")
        except Exception:
            return self._err("bad_json", "Invalid JSON")
        path = self.path

        if path == "/api/quit":
            self._send({"ok": True})
            threading.Thread(target=self.server.shutdown, daemon=True).start()
            return
        try:
            if path == "/api/last":      # remember which config was last edited / uploaded
                name = data.get("name")
                if name is not None and not NAME_RE.match(name):
                    return self._err("bad_name", "Invalid name")
                write_state(last=name)
                return self._send({"ok": True})
            if path == "/api/draft":     # remember the working copy (even unsaved edits)
                cfg = data.get("config")
                if not isinstance(cfg, dict) or not isinstance(cfg.get("layers"), list) or len(json.dumps(cfg)) > 500_000:
                    return self._err("bad_request", "Bad draft")
                write_state(draft={"name": data.get("name"), "config": cfg, "layer": int(data.get("layer", 0))})
                return self._send({"ok": True})
            if path == "/api/parse":     # read a YAML text (e.g. an exported layer) without saving it
                text = data["text"]
                if len(text) > 500_000:
                    return self._err("bad_yaml", "File too large")
                try:
                    return self._send(cfg_from_raw(yaml.safe_load(text)))
                except Exception as e:
                    return self._err("bad_yaml", f"Unreadable YAML: {e}")
            if path == "/api/yaml":
                return self._send({"yaml": render_yaml(data["config"])})
            if path == "/api/save":
                name = data.get("name", "")
                if not NAME_RE.match(name):
                    return self._err("bad_name", "Invalid name (use letters, numbers, space, . _ -)")
                (CONFIGS / f"{name}.yaml").write_text(render_yaml(data["config"]))
                return self._send({"ok": True, "name": name})
            if path == "/api/validate":
                code, out = run_tool(["validate"], stdin=render_yaml(data["config"]))
                return self._send({"ok": code == 0, "message": out})
            if path == "/api/upload":
                text = render_yaml(data["config"])
                code, out = privileged(["upload"], text=text)
                resp = {"ok": code == 0, "message": out}
                if code == 0:
                    resp["code"] = "uploaded"
                elif TOOL is not None:
                    last = DATA / "last_upload.yaml"
                    last.write_text(text)
                    resp["terminal_cmd"] = f"sudo {shlex.quote(str(TOOL))} --vendor-id {VENDOR} upload {shlex.quote(str(last))}"
                return self._send(resp)
            if path == "/api/led":
                idx = int(data.get("index", 0))
                code, out = privileged(["led", str(idx)])
                return self._send({"ok": code == 0, "message": out, "code": "led_set" if code == 0 else None, "index": idx})
        except (KeyError, TypeError, ValueError) as e:
            return self._err("bad_request", f"Bad request: {e}")
        self._err("not_found", "not found", 404)


def main():
    global PORT, TOOL, CONFIGS, DATA, STATE_FILE
    ap = argparse.ArgumentParser(description="MacroPad UI")
    ap.add_argument("--port", type=int, default=int(os.environ.get("MACROPAD_PORT", 8777)))
    ap.add_argument("--no-open", action="store_true", help="do not open the browser")
    ap.add_argument("--tool", help="path to ch57x-keyboard-tool")
    ap.add_argument("--configs", help="folder for your YAML configs")
    a = ap.parse_args()

    PORT = a.port
    TOOL = find_tool(a.tool)
    DATA = Path(os.environ.get("MACROPAD_DATA") or default_data_dir())
    CONFIGS = Path(a.configs) if a.configs else DATA / "configs"
    DATA.mkdir(parents=True, exist_ok=True)
    STATE_FILE = DATA / "state.json"
    seed_configs()

    srv = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    url = f"http://127.0.0.1:{PORT}"
    print(f"MacroPad UI running at {url}  (Ctrl+C to quit)")
    print(f"  tool:    {TOOL or 'NOT FOUND - install ch57x-keyboard-tool or set MACROPAD_TOOL'}")
    print(f"  configs: {CONFIGS}")
    if not a.no_open:
        webbrowser.open(url)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
